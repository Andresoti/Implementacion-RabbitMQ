CREATE TABLE IF NOT EXISTS pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente VARCHAR(255) NOT NULL,
    producto VARCHAR(255) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 10000),
    estado VARCHAR(255) NOT NULL
);

CREATE TABLE outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id VARCHAR(36) NOT NULL,
 destination VARCHAR(10) NOT NULL CHECK(destination IN ('ORDER','TICKET')),
 payload TEXT NOT NULL,
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 published_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(event_id,destination)
);
CREATE INDEX outbox_pending_idx ON outbox(next_attempt_at,id) WHERE published_at IS NULL;
